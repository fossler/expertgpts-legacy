def _symbol(primary: str, ink: str) -> str:
    """Build the symbol elements.

    Args:
        primary: Color of the speech bubble
        ink: Color of the mortarboard and tassel

    Returns:
        str: SVG elements of the 64x64 symbol
    """
    return (
        f'<path d="{BUBBLE_PATH}" fill="{primary}" fill-rule="evenodd"/>'
        f'<path d="{MORTARBOARD_PATH}" fill="{ink}"/>'
        f'<path d="{TASSEL_CORD_PATH}" fill="none" stroke="{ink}" '
        'stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"/>'
        f'<rect x="53.5" y="29" width="5" height="7" rx="1.5" fill="{ink}"/>'
    )


def icon_svg(primary: str, ink: str) -> str:
    """Build the square symbol, e.g. for the favicon.

    Args:
        primary: Color of the speech bubble
        ink: Color of the mortarboard and tassel

    Returns:
        str: SVG markup
    """
    return SVG_OPEN.format(w=64, h=64) + _symbol(primary, ink) + "</svg>"


def logo_svg(primary: str, ink: str) -> str:
    """Build the full logo: symbol above wordmark and tagline.

    Args:
        primary: Color of the speech bubble and of "GPTs"
        ink: Color of the mortarboard, "Expert" and "legacy"

    Returns:
        str: SVG markup
    """
    return (
        SVG_OPEN.format(w=LOGO_WIDTH, h=LOGO_HEIGHT)
        + f'<g transform="translate({SYMBOL_X} {SYMBOL_Y}) scale({SYMBOL_SCALE})">'
        + _symbol(primary, ink)
        + "</g>"
        + f'<g transform="translate({WORDMARK_X} {WORDMARK_BASELINE})">'
        f'<path d="{WORDMARK_EXPERT_PATH}" fill="{ink}"/>'
        f'<path d="{WORDMARK_GPTS_PATH}" fill="{primary}"/>'
        f'<path d="{TAGLINE_PATH}" fill="{ink}" '
        f'transform="translate({TAGLINE_X} {TAGLINE_BASELINE})"/>'
        "</g></svg>"
    )


def _is_dark(hex_color: str) -> bool:
    """Tell whether a "#RRGGBB" color is dark (relative luminance below 0.5)."""
    try:
        r, g, b = (int(hex_color.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4))
    except ValueError:
        return False
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255 < 0.5


def theme_logo() -> tuple[str, str]:
    """Build logo and icon in the brand colors, readable on the active theme.

    Returns:
        tuple: (logo SVG, icon SVG)
    """
    theme = get_theme_settings()
    ink = BRAND_INK
    if _is_dark(theme.get("backgroundColor", "#FFFFFF")):
        ink = theme.get("textColor", "#FFFFFF")
    return logo_svg(BRAND_PRIMARY, ink), icon_svg(BRAND_PRIMARY, ink)
